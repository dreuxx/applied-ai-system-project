const prefixes = [
  ["Etiqueta desconocida: ", "Unknown label: "],
  ["Fila inválida: ", "Invalid row: "],
  ["Revisa el perfil de la fila ", "Check the profile in row "],
];
function t(lang, key, values = {}) {
  const text = strings[lang]?.[key] ?? strings.es[key];
  if (text === undefined) throw Error("Texto desconocido: " + key);
  return text.replace(/\{(\w+)\}/g, (_, name) => String(values[name]));
}
// Genre, mood and instrument names are stored in English.
const label = (lang, name) => (lang === "en" ? name : tr(name));
function message(lang, text) {
  if (lang !== "en" || typeof text !== "string") return text;
  const dot = text.endsWith(".") ? "." : "",
    core = dot ? text.slice(0, -1) : text;
  if (Object.hasOwn(phrases, core)) return phrases[core] + dot;
  for (const [from, to] of prefixes)
    if (text.startsWith(from)) return to + text.slice(from.length);
  return text;
}
// First tag of an Accept-Language header. Spanish unless English is listed first.
const pick = (header) => (/^\s*en\b/i.test(header ?? "") ? "en" : "es");
module.exports = { languages, strings, phrases, t, label, message, pick };
